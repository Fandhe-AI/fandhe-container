//! CRI の `DnsConfig` を検証し、コンテナの `/etc/resolv.conf` の内容を作る純粋関数
//! （CRI-2・NET-5・REPAIR-2・REPAIR-3。#2665）。
//!
//! ファイルシステムに触れない。呼び出し元は [`super::spec`]（検証と `mounts[]` の出力）と
//! [`super::SpecBundleProvider`]（bundle への書き込み）。出力は検証済みの [`ResolvConf`] だけで、生の文字列を
//! 手で組んで書き出さない。
//!
//! **注入の防止**: servers は `IpAddr` に parse できたものの `Display` だけを書き、search・option は許可する文字集合
//! （英数字・`-`・`_`・`.`、option は `:` も）の外を拒否する。空白・改行・NUL・`#`・`;` は届かない。
//! エラー文言は固定文言とフィールド名だけで、入力値を含めない。
//!
//! **未実装・簡易実装（REPAIR-3）**:
//! - zone つきの IPv6（`fe80::1%eth0`）は `IpAddr` に parse できず `INVALID_ARGUMENT` にする。
//! - 3 つのリストがすべて空の `DnsConfig` は「指定なし」と同じに扱い、ファイルを作らない（空の resolv.conf は
//!   glibc を 127.0.0.1 へ落とす。ホストの resolv.conf も写さない）。
//! - 上限のうち search の 32 件・合計 2048 バイト・1 件 253 バイトは kubelet（`v1.37.1` で照合）と同じ値。servers 32 件
//!   （kubelet は 3 件）・options 32 件 / 1 件 64 バイト（kubelet には件数・長さの上限が無い）・生成物 8 KiB は本実装独自の上限。
//!   kubelet は上限超過を切り詰めて CRI へ渡すが、本実装は切り詰めず `INVALID_ARGUMENT` にする（kubelet 経由なら上限内で届く）。
//!   glibc が使う先頭 3 件への切り詰めもしない。詳細は `docs/design/cri-config-acceptance.md`「dns_config の受け入れ方式」。

use std::net::IpAddr;

use crate::error::CriError;
use crate::runtime::v1::DnsConfig;

/// nameserver の件数上限（net の `MAX_DNS_SERVERS` と同値）。本実装独自の上限（kubelet は 3 件）。
pub const MAX_DNS_SERVERS: usize = 32;
/// search ドメインの件数上限（kubelet と同値）。
pub const MAX_DNS_SEARCHES: usize = 32;
/// search ドメイン 1 件の長さ上限（バイト。DNS 名の上限。kubelet と同値）。
pub const MAX_DNS_SEARCH_BYTES: usize = 253;
/// `search` 行の値の合計長の上限（バイト。kubelet の上限と同値）。
pub const MAX_DNS_SEARCH_TOTAL_BYTES: usize = 2048;
/// resolver option の件数上限。本実装独自の上限（kubelet には無い）。
pub const MAX_DNS_OPTIONS: usize = 32;
/// resolver option 1 件の長さ上限（バイト）。本実装独自の上限（kubelet には無い）。
pub const MAX_DNS_OPTION_BYTES: usize = 64;
/// 生成する resolv.conf 全体の長さ上限（バイト）。本実装独自の上限（kubelet には無い）。
pub const MAX_RESOLV_CONF_BYTES: usize = 8192;

const HEADER: &str = "# Generated by fandhe-container (CRI-2)\n";

/// 検証済みの resolv.conf の内容（REPAIR-2）。[`render`] 以外からは作れない。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvConf(Vec<u8>);

impl ResolvConf {
    /// ファイルへ書くバイト列。
    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }
}

fn invalid(field: &'static str) -> CriError {
    CriError::invalid_argument(format!("{field} is invalid"))
}

fn search_ok(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_DNS_SEARCH_BYTES
        && s.split('.').all(|l| {
            !l.is_empty()
                && l.len() <= 63
                && l.bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
        })
}

fn option_ok(o: &str) -> bool {
    !o.is_empty()
        && o.len() <= MAX_DNS_OPTION_BYTES
        && o.bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b':'))
}

/// `DnsConfig` を検証して resolv.conf の内容を作る。3 リストがすべて空なら `Ok(None)`。
///
/// 件数・長さは確保の前に検証し、1 件でも不正なら全体を拒否する（all-or-nothing）。
pub fn render(dns: &DnsConfig) -> Result<Option<ResolvConf>, CriError> {
    if dns.servers.is_empty() && dns.searches.is_empty() && dns.options.is_empty() {
        return Ok(None);
    }
    if dns.servers.len() > MAX_DNS_SERVERS {
        return Err(invalid("dns_config.servers"));
    }
    if dns.searches.len() > MAX_DNS_SEARCHES {
        return Err(invalid("dns_config.searches"));
    }
    if dns.options.len() > MAX_DNS_OPTIONS {
        return Err(invalid("dns_config.options"));
    }
    let servers = dns
        .servers
        .iter()
        .map(|s| {
            s.parse::<IpAddr>()
                .map_err(|_| invalid("dns_config.servers"))
        })
        .collect::<Result<Vec<_>, _>>()?;
    if !dns.searches.iter().all(|s| search_ok(s)) {
        return Err(invalid("dns_config.searches"));
    }
    // 区切りの空白を含めた `search` 行の値の長さ（checked 演算）。
    let total = dns
        .searches
        .iter()
        .try_fold(0usize, |acc, s| acc.checked_add(s.len())?.checked_add(1))
        .ok_or_else(|| invalid("dns_config.searches"))?;
    if total.saturating_sub(1) > MAX_DNS_SEARCH_TOTAL_BYTES {
        return Err(invalid("dns_config.searches"));
    }
    if !dns.options.iter().all(|o| option_ok(o)) {
        return Err(invalid("dns_config.options"));
    }

    let mut out = String::from(HEADER);
    for ip in &servers {
        out.push_str(&format!("nameserver {ip}\n"));
    }
    if !dns.searches.is_empty() {
        out.push_str("search ");
        out.push_str(&dns.searches.join(" "));
        out.push('\n');
    }
    if !dns.options.is_empty() {
        out.push_str("options ");
        out.push_str(&dns.options.join(" "));
        out.push('\n');
    }
    if out.len() > MAX_RESOLV_CONF_BYTES {
        return Err(invalid("dns_config"));
    }
    Ok(Some(ResolvConf(out.into_bytes())))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::error::CriErrorCode;

    fn dns(servers: &[&str], searches: &[&str], options: &[&str]) -> DnsConfig {
        let v = |x: &[&str]| x.iter().map(|s| (*s).to_owned()).collect();
        DnsConfig {
            servers: v(servers),
            searches: v(searches),
            options: v(options),
        }
    }

    fn text(d: &DnsConfig) -> String {
        String::from_utf8(render(d).unwrap().unwrap().as_bytes().to_vec()).unwrap()
    }

    /// CRI-2・NET-5: IPv4/IPv6 混在・search・options の完全な出力。
    #[test]
    fn renders_all_sections_in_fixed_order() {
        let d = dns(
            &["10.0.0.10", "2001:db8::1"],
            &["svc.cluster.local", "cluster.local"],
            &["ndots:5", "timeout:2"],
        );
        assert_eq!(
            text(&d),
            "# Generated by fandhe-container (CRI-2)\n\
             nameserver 10.0.0.10\n\
             nameserver 2001:db8::1\n\
             search svc.cluster.local cluster.local\n\
             options ndots:5 timeout:2\n"
        );
    }

    #[test]
    fn all_empty_is_none_and_searches_only_has_only_that_line() {
        assert!(render(&DnsConfig::default()).unwrap().is_none());
        assert_eq!(
            text(&dns(&[], &["example.com"], &[])),
            "# Generated by fandhe-container (CRI-2)\nsearch example.com\n"
        );
    }

    #[test]
    fn rejects_invalid_values_without_echoing_them() {
        let long_label = "a".repeat(64);
        let long_option = "a".repeat(65);
        let bad = [
            dns(&["not-an-ip"], &[], &[]),
            dns(&["fe80::1%eth0"], &[], &[]),
            dns(&["1.1.1.1\nnameserver 8.8.8.8"], &[], &[]),
            dns(&[], &["a b"], &[]),
            dns(&[], &["a\nb"], &[]),
            dns(&[], &["a\0b"], &[]),
            dns(&[], &["a#b"], &[]),
            dns(&[], &["a..b"], &[]),
            dns(&[], &["example.com."], &[]),
            dns(&[], &[""], &[]),
            dns(&[], &[long_label.as_str()], &[]),
            dns(&[], &[], &["ndots:5 x"]),
            dns(&[], &[], &["a\nb"]),
            dns(&[], &[], &[""]),
            dns(&[], &[], &[long_option.as_str()]),
        ];
        for d in &bad {
            let e = render(d).unwrap_err();
            assert_eq!(e.code(), CriErrorCode::InvalidArgument);
            let msg = format!("{e:?}");
            assert!(
                !msg.contains("not-an-ip") && !msg.contains("nameserver 8"),
                "{msg}"
            );
        }
    }

    #[test]
    fn count_limits_are_exact() {
        let ips: Vec<String> = (0..MAX_DNS_SERVERS)
            .map(|i| format!("10.0.0.{i}"))
            .collect();
        let refs: Vec<&str> = ips.iter().map(String::as_str).collect();
        assert!(render(&dns(&refs, &[], &[])).is_ok());
        let mut over = refs.clone();
        over.push("10.0.1.1");
        assert!(render(&dns(&over, &[], &[])).is_err());

        let opts: Vec<String> = (0..=MAX_DNS_OPTIONS).map(|i| format!("o{i}")).collect();
        let o: Vec<&str> = opts.iter().map(String::as_str).collect();
        assert!(render(&dns(&[], &[], &o[..MAX_DNS_OPTIONS])).is_ok());
        assert!(render(&dns(&[], &[], &o)).is_err());
    }

    #[test]
    fn search_total_length_limit_is_exact() {
        let full = format!(
            "{}.{}.{}.{}",
            "a".repeat(63),
            "b".repeat(63),
            "c".repeat(63),
            "d".repeat(61)
        );
        assert_eq!(full.len(), 253);
        // 8 件: 8 * 253 + 7 = 2031 バイト。
        let ok: Vec<&str> = vec![full.as_str(); 8];
        assert!(render(&dns(&[], &ok, &[])).is_ok());
        // 9 件目に 20 バイトを足すと 2031 + 1 + 20 = 2052 > 2048。
        let extra = "x".repeat(20);
        let mut over = ok.clone();
        over.push(extra.as_str());
        assert!(render(&dns(&[], &over, &[])).is_err());
        // 2048 バイトちょうどは通る（2031 + 1 + 16）。
        let fit = "x".repeat(16);
        let mut exact = ok;
        exact.push(fit.as_str());
        assert!(render(&dns(&[], &exact, &[])).is_ok());
    }
}
